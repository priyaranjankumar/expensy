// Helper function to dynamically map an account name, payment method name or description to an icon
export const getAssetLogo = (name: string): React.ReactElement => {
    const cleanName = name.toLowerCase().replace(/[\s-]/g, '');
    
    // Bank checks
    if (cleanName.includes('sbi') || cleanName.includes('statebank')) return <SbiIcon className="w-8 h-8 rounded" />;
    if (cleanName.includes('hdfc')) return <HdfcIcon className="w-8 h-8 rounded" />;
    if (cleanName.includes('icici')) return <IciciIcon className="w-8 h-8 rounded" />;
    if (cleanName.includes('axis')) return <AxisIcon className="w-8 h-8 rounded" />;
    if (cleanName.includes('kotak')) return <KotakIcon className="w-8 h-8 rounded" />;
    if (cleanName.includes('yesbank') || cleanName.includes('yes bank')) return <YesBankIcon className="w-8 h-8 rounded" />;
    if (cleanName.includes('federal')) return <FederalBankIcon className="w-8 h-8 rounded" />;
    if (cleanName.includes('idfc')) return <IdfcBankIcon className="w-8 h-8 rounded" />;
    if (cleanName.includes('standardchartered') || cleanName.includes('standardcharted')) return <StandardCharteredIcon className="w-8 h-8 rounded" />;
    if (cleanName.includes('hsbc')) return <HsbcIcon className="w-8 h-8 rounded" />;
    if (cleanName.includes('indusind') || cleanName.includes('induslnd')) return <IndusindIcon className="w-8 h-8 rounded" />;
    
    // Wallet/UPI checks
    if (cleanName.includes('gpay') || cleanName.includes('googlepay')) return <GpayIcon className="w-8 h-8 rounded" />;
    if (cleanName.includes('phonepe')) return <PhonepeIcon className="w-8 h-8 rounded" />;
    if (cleanName.includes('paytm')) return <PaytmIcon className="w-8 h-8 rounded" />;
    if (cleanName.includes('cred')) return <CredIcon className="w-8 h-8 rounded" />;

    // Fallback
    return <GenericBankIcon className="w-8 h-8 text-indigo-500" />;
};
